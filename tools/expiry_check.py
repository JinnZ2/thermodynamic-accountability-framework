#!/usr/bin/env python3
# tools/expiry_check.py -- CC0, stdlib only, python >= 3.7
# Provenance: co-authored (JinnZ2 + Claude), 2026-11-10.
#
# Checks docs/expiry_register.json against the tree and renders
# docs/expiry_register.md. It reads; it changes no module's behavior.
#
#   python tools/expiry_check.py            check, print counts
#   python tools/expiry_check.py --write    also write docs/expiry_register.md
#
# What it checks:
#   - every slot's anchor text is still on the stated file:line
#   - a filled expiry_condition has a non-VOID expiry_source; a VOID one has VOID
#   - every stated_partial_source file:line exists
# What it does not check: whether a quoted source says what the row claims,
# and whether the slot list is complete (the slot rule is applied by hand).
#
# Exit 0 = all rows match the tree, 1 = at least one mismatch.

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "docs", "expiry_register.json")
OUT = os.path.join(ROOT, "docs", "expiry_register.md")
VOID = "VOID"


def _line(path, n):
    try:
        with open(os.path.join(ROOT, path), encoding="utf-8") as f:
            lines = f.read().split("\n")
    except OSError:
        return None
    return lines[n - 1] if 0 < n <= len(lines) else None


def is_filled(slot):
    return not slot["expiry_condition"].startswith(VOID)


def check(reg):
    problems = []
    for s in reg["slots"]:
        got = _line(s["file"], s["line"])
        if got is None or s["anchor"] not in got:
            problems.append("%s: anchor not on %s:%d" % (s["slot"], s["file"], s["line"]))
        if is_filled(s) == (s["expiry_source"] == VOID):
            problems.append("%s: expiry_condition and expiry_source disagree on VOID" % s["slot"])
        if s["status"] not in ("PENDING", "UNKNOWN"):
            problems.append("%s: status %s" % (s["slot"], s["status"]))
        for ref in re.findall(r"([\w./-]+\.\w+):(\d+)", s.get("stated_partial_source") or ""):
            if _line(ref[0], int(ref[1])) is None:
                problems.append("%s: partial source %s:%s not in tree" % (s["slot"], ref[0], ref[1]))
    for row in reg.get("sweep_rank", {}).get("rows", []):
        got = _line(row["file"], row["line"])
        if got is None or row["anchor"] not in got:
            problems.append("sweep rank %d: anchor not on %s:%d" % (row["rank"], row["file"], row["line"]))
    for s in reg["slots"]:
        if "in_sweep_rank" not in s:
            problems.append("%s: no in_sweep_rank" % s["slot"])
    return problems


def folder(path):
    return path.split("/")[0] if "/" in path else "(root)"


def counts(reg):
    by = {}
    for s in reg["slots"]:
        row = by.setdefault(folder(s["file"]), {"PENDING": 0, "UNKNOWN": 0, "filled": 0, "void": 0, "void_with_partial": 0})
        row[s["status"]] += 1
        if is_filled(s):
            row["filled"] += 1
        else:
            row["void"] += 1
            if s.get("stated_partial"):
                row["void_with_partial"] += 1
    return by


def render(reg):
    slots = reg["slots"]
    by = counts(reg)
    tot = {k: sum(r[k] for r in by.values()) for k in ("PENDING", "UNKNOWN", "filled", "void", "void_with_partial")}
    out = ["# Expiry register -- stage 1", "",
           "Generated by `python tools/expiry_check.py --write` from `docs/expiry_register.json`.",
           "Built against commit `%s`. Do not edit this file by hand." % reg["built_against_commit"][:12], "",
           "Rule: `expiry_condition` is filled only where the slot's own text, docstring or",
           "cited source states an instrument class, sensitivity or protocol AND what its",
           "null result does to the entry. Anything else is VOID. Nothing was inferred.",
           "`partial` below is text that names a protocol or a resolution condition without",
           "a null-result rule. It is not an exit and it is counted as VOID.", "",
           "Slot rule: " + reg["slot_rule"], "",
           "## Two slot rules, two counts", "",
           "| rule | PENDING | UNKNOWN | what it counts |", "|---|---|---|---|"]
    cmp_ = reg["slot_rule_comparison"]
    for k in cmp_:
        if k != "decision":
            out.append("| %s | %d | %d | %s |" % (k, cmp_[k]["PENDING"], cmp_[k]["UNKNOWN"], cmp_[k]["rule"].replace("|", "/")))
    out += ["", cmp_["decision"], "",
           "## Counts", "",
           "| folder | PENDING | UNKNOWN | filled | VOID | of which VOID with partial |", "|---|---|---|---|---|---|"]
    for f in sorted(by):
        r = by[f]
        out.append("| %s | %d | %d | %d | %d | %d |" % (f, r["PENDING"], r["UNKNOWN"], r["filled"], r["void"], r["void_with_partial"]))
    out.append("| total | %d | %d | %d | %d | %d |" % (tot["PENDING"], tot["UNKNOWN"], tot["filled"], tot["void"], tot["void_with_partial"]))
    out += ["", "## Slots", "", "| slot | file:line | status | expiry filled? | source |", "|---|---|---|---|---|"]
    for s in slots:
        out.append("| %s %s | `%s:%d` | %s | %s | %s |" % (
            s["slot"], s["what"].replace("|", "/"), s["file"], s["line"], s["status"],
            "yes" if is_filled(s) else "VOID", s["expiry_source"]))
    out += ["", "## VOID slots with partial text (not an exit)", "", "| slot | what the text states | where |", "|---|---|---|"]
    for s in slots:
        if not is_filled(s) and s.get("stated_partial"):
            out.append("| %s | %s | `%s` |" % (s["slot"], s["stated_partial"].replace("|", "/"), s["stated_partial_source"]))
    out += ["", "## VOID slots in code or data that reaches an output", "",
            "Read from the code by hand. `in_sweep_rank` cross-references the rank list below.", "",
            "| slot | file:line | how it reaches an output | in_sweep_rank |", "|---|---|---|---|"]
    for s in slots:
        v = s.get("verdict_reaching") or ""
        if not is_filled(s) and v.startswith(("yes", "written", "carried")):
            out.append("| %s | `%s:%d` | %s | %s |" % (s["slot"], s["file"], s["line"], v.replace("|", "/"), s["in_sweep_rank"]))
    sw = reg["sweep_rank"]
    out += ["", "## Default-sweep rank rows", "", sw["source"], "",
            "None of these sites holds a PENDING or UNKNOWN value: each is a default that",
            "fills a missing input. They are not slots under the rule above and carry no",
            "expiry fields. Slots that pass through one are marked in the table above.", "",
            "| rank | file:line | what the default does | slots passing through |", "|---|---|---|---|"]
    for row in sw["rows"]:
        through = [s["slot"] + (" (not traced)" if s["in_sweep_rank"].startswith("near") else "") for s in slots if s["in_sweep_rank"] != "no"
                   and ("%s:" % row["file"].split("/")[-1]) in s["in_sweep_rank"]
                   and re.search(r":(\d+)-(\d+)", s["in_sweep_rank"])
                   and int(re.search(r":(\d+)-(\d+)", s["in_sweep_rank"]).group(1)) <= row["line"] <= int(re.search(r":(\d+)-(\d+)", s["in_sweep_rank"]).group(2))]
        out.append("| %d | `%s:%d` | %s | %s |" % (row["rank"], row["file"], row["line"], row["what"], ", ".join(through) or "none"))
    out += ["", "## Status vocabulary addition", ""]
    for k, v in reg["status_vocabulary_addition"].items():
        out.append("- `%s`: %s" % (k, v))
    return "\n".join(out) + "\n"


def main(argv):
    with open(REG, encoding="utf-8") as f:
        reg = json.load(f)
    problems = check(reg)
    for p in problems:
        print("MISMATCH  " + p)
    by = counts(reg)
    n = len(reg["slots"])
    filled = sum(r["filled"] for r in by.values())
    print("slots %d  PENDING %d  UNKNOWN %d  filled %d  VOID %d  (VOID with partial %d)" % (
        n, sum(r["PENDING"] for r in by.values()), sum(r["UNKNOWN"] for r in by.values()),
        filled, n - filled, sum(r["void_with_partial"] for r in by.values())))
    if "--write" in argv:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(render(reg))
        print("wrote docs/expiry_register.md")
    print("%d mismatch(es)" % len(problems))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
